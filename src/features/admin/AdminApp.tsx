import React, { useEffect, useRef, useState } from 'react';
import { AdminLayout, type AdminSection } from './components/AdminLayout';
import { OverviewPage } from './pages/OverviewPage';
import { MenuManagerPage } from './pages/MenuManagerPage';
import { TablesPage } from './pages/TablesPage';
import { GuestServicesPage } from './pages/GuestServicesPage';
import { GuestInboxPage } from './pages/GuestInboxPage';
import { RestaurantSettingsPage } from './pages/RestaurantSettingsPage';
import { createDefaultSetup, type DemoSetup, type GuestFeedback, type GuestRequest } from '../../data/demoStore';
import { supabase } from '../../lib/supabase';
import { deleteCloudRequest, getPageRestaurantSlug, getRestaurantId, loadCloudAdminSetup, loadCloudInbox, publishCloudSetup, saveCloudDraft, updateCloudFeedback } from '../../lib/restaurantCloud';
import { Moon, Sun } from 'lucide-react';
import requestBellUrl from '../../assets/guest-request-bell.mp3';

const sections: AdminSection[] = ['overview', 'menu', 'tables', 'services', 'inbox', 'settings'];
const initialSection = (): AdminSection => {
  const query = new URLSearchParams(window.location.search).get('section');
  return sections.includes(query as AdminSection) ? query as AdminSection : 'overview';
};

const setupSnapshot = (value: DemoSetup) => JSON.stringify({
  ...value,
  // Table row UUIDs are generated by Supabase; only their user-controlled fields matter here.
  tables: value.tables.map(({ number, isActive }) => ({ number, isActive })),
});

function startContinuousRequestBell(): () => void {
  const audio = new Audio(requestBellUrl);
  audio.loop = true;
  audio.volume = 1;
  void audio.play().catch((error: unknown) => console.warn('Could not play the guest request alert sound:', error));
  return () => {
    audio.pause();
    audio.currentTime = 0;
  };
}

export const AdminApp: React.FC = () => {
  const [section, setSection] = useState<AdminSection>(initialSection);
  const [setup, setSetup] = useState<DemoSetup>(createDefaultSetup);
  const [requests, setRequests] = useState<GuestRequest[]>([]);
  const [feedback, setFeedback] = useState<GuestFeedback[]>([]);
  const [notice, setNotice] = useState('');
  const [publishedAt, setPublishedAt] = useState<string | null>(null);
  const [savedSetupSnapshot, setSavedSetupSnapshot] = useState('');
  const [isPublishing, setIsPublishing] = useState(false);
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [authReady, setAuthReady] = useState(false);
  const [userId, setUserId] = useState<string | null>(null);
  const [cloudLoading, setCloudLoading] = useState(false);
  const [cloudError, setCloudError] = useState('');
  const [theme, setTheme] = useState<'light' | 'dark'>('light');
  const [requestAlert, setRequestAlert] = useState<GuestRequest | null>(null);
  const [acknowledgingRequestId, setAcknowledgingRequestId] = useState<string | null>(null);
  const seenRequestIdsRef = useRef<Set<string> | null>(null);
  const stopRequestBellRef = useRef<(() => void) | null>(null);
  const ringingRequestIdRef = useRef<string | null>(null);

  useEffect(() => {
    if (!requestAlert) {
      stopRequestBellRef.current?.();
      stopRequestBellRef.current = null;
      ringingRequestIdRef.current = null;
      return;
    }
    if (ringingRequestIdRef.current === requestAlert.id) return;
    stopRequestBellRef.current?.();
    ringingRequestIdRef.current = requestAlert.id;
    stopRequestBellRef.current = startContinuousRequestBell();
    return () => {
      if (ringingRequestIdRef.current === requestAlert.id) {
        stopRequestBellRef.current?.();
        stopRequestBellRef.current = null;
        ringingRequestIdRef.current = null;
      }
    };
  }, [requestAlert?.id]);

  useEffect(() => {
    if (!supabase) { setAuthReady(true); return; }
    void supabase.auth.getSession().then(({ data }) => { setUserId(data.session?.user.id ?? null); setAuthReady(true); }).catch(() => { setCloudError('Could not connect to the restaurant service. Check your connection and refresh.'); setAuthReady(true); });
    const { data: listener } = supabase.auth.onAuthStateChange((_event, session) => setUserId(session?.user.id ?? null));
    return () => listener.subscription.unsubscribe();
  }, []);

  useEffect(() => {
    if (!userId || !supabase) return;
    const client = supabase;
    let cancelled = false;
    let inboxChannel: ReturnType<typeof client.channel> | null = null;
    setCloudLoading(true);
    setCloudError('');
    Promise.all([loadCloudAdminSetup(createDefaultSetup()), loadCloudInbox()]).then(([cloudState, inbox]) => {
      if (cancelled) return;
      setSetup(cloudState.setup);
      setSavedSetupSnapshot(setupSnapshot(cloudState.publishedSetup));
      setRequests(inbox.requests);
      setFeedback(inbox.feedback);
      seenRequestIdsRef.current = new Set(inbox.requests.map((request) => request.id));
    }).catch(() => { if (!cancelled) setCloudError('Could not load this restaurant workspace. Check your access and try again.'); })
      .finally(() => { if (!cancelled) setCloudLoading(false); });
    const refreshInbox = () => {
      void loadCloudInbox().then((inbox) => {
        if (cancelled) return;
        const seenIds = seenRequestIdsRef.current;
        const arrivingRequests = seenIds ? inbox.requests.filter((request) => !seenIds.has(request.id)) : [];
        seenRequestIdsRef.current = new Set(inbox.requests.map((request) => request.id));
        setRequests(inbox.requests);
        setFeedback(inbox.feedback);
        setRequestAlert((current) => current && inbox.requests.some((request) => request.id === current.id)
          ? current
          : arrivingRequests[0] ?? null);
      }).catch(() => undefined);
    };
    const refreshFallback = window.setInterval(refreshInbox, 10000);
    void getRestaurantId(getPageRestaurantSlug()).then((restaurantId) => {
      if (cancelled) return;
      inboxChannel = client.channel(`admin-inbox-${restaurantId}`)
        .on('postgres_changes', { event: '*', schema: 'public', table: 'guest_requests', filter: `restaurant_id=eq.${restaurantId}` }, refreshInbox)
        .on('postgres_changes', { event: '*', schema: 'public', table: 'guest_feedback', filter: `restaurant_id=eq.${restaurantId}` }, refreshInbox)
        .subscribe();
    }).catch(() => setCloudError('Could not subscribe to guest inbox updates.'));
    return () => {
      cancelled = true;
      window.clearInterval(refreshFallback);
      if (inboxChannel) void client.removeChannel(inboxChannel);
    };
  }, [userId]);

  const saveDraft = async () => {
    try { await saveCloudDraft(setup); setNotice('Draft saved. Guests still see the last published version.'); }
    catch { setCloudError('Could not save the draft. Please try again.'); }
    window.setTimeout(() => setNotice(''), 5000);
  };

  const publish = async () => {
    setIsPublishing(true);
    try {
      const now = await publishCloudSetup(setup);
      setPublishedAt(now);
      setSavedSetupSnapshot(setupSnapshot(setup));
      setNotice('Published. Customer pages now show the latest restaurant data.');
      setCloudError('');
    }
    catch {
      console.error('Could not publish restaurant changes.');
      setCloudError('Could not publish these changes. Check the form and your access, then try again.');
    }
    finally { setIsPublishing(false); }
    window.setTimeout(() => setNotice(''), 5000);
  };

  const updateServices = async (nextSetup: DemoSetup) => {
    setSetup(nextSetup);
    try { await publishCloudSetup(nextSetup); setNotice('Guest section visibility updated for this restaurant.'); }
    catch { setCloudError('Could not update guest services. Please try again.'); }
    window.setTimeout(() => setNotice(''), 4000);
  };

  const acknowledgeRequest = async (id: string) => {
    setAcknowledgingRequestId(id);
    setCloudError('');
    try {
      await deleteCloudRequest(id);
      const remainingRequests = requests.filter((row) => row.id !== id);
      setRequests(remainingRequests);
      seenRequestIdsRef.current?.delete(id);
      setRequestAlert((current) => current?.id === id ? remainingRequests[0] ?? null : current);
    } catch (error) {
      setCloudError('Could not remove this request. Check your connection and try again.');
    } finally {
      setAcknowledgingRequestId(null);
    }
  };
  const updateFeedback = (id: string, status: GuestFeedback['status']) => { setFeedback((rows) => rows.map((row) => row.id === id ? { ...row, status } : row)); void updateCloudFeedback(id, status).catch(() => setCloudError('Could not update feedback status. Please try again.')); };

  const signIn = async (event: React.FormEvent) => {
    event.preventDefault();
    if (!supabase) return;
    setCloudError('');
    try {
      const { error } = await supabase.auth.signInWithPassword({ email, password });
      if (error) setCloudError('Sign-in failed. Check your email and password, then try again.');
    } catch { setCloudError('Could not sign in. Check your connection and try again.'); }
  };

  if (!authReady || cloudLoading) return <div className="flex min-h-screen flex-col items-center justify-center gap-3 bg-[#F6F5F2] p-6 text-center text-sm text-[#51483F]"><span className="h-8 w-8 animate-spin rounded-full border-2 border-[#D8C7B6] border-t-[#8C5138]" /><p>{!authReady ? 'Connecting to the restaurant service…' : 'Loading restaurant workspace…'}</p>{cloudError && <p role="alert" className="max-w-lg text-red-700">{cloudError}</p>}</div>;
  const themeToggle = <button type="button" onClick={() => setTheme((value) => value === 'light' ? 'dark' : 'light')} aria-label={`Switch to ${theme === 'light' ? 'dark' : 'light'} mode`} className="inline-flex min-h-10 items-center gap-2 rounded-xl border border-[#DCD3C8] bg-white px-3 text-sm font-semibold text-[#30271F] shadow-sm hover:bg-[#F8F6F2]"><span aria-hidden="true">{theme === 'light' ? <Moon size={16} /> : <Sun size={16} />}</span>{theme === 'light' ? 'Dark mode' : 'Light mode'}</button>;
  if (!supabase) return <div data-admin-theme={theme} className="admin-theme min-h-screen bg-[#F6F5F2] p-4 text-[#211D19]"><div className="mx-auto flex max-w-lg justify-end pt-4">{themeToggle}</div><div className="mx-auto mt-8 max-w-lg rounded-2xl border bg-white p-6"><h1 className="text-xl font-bold">Online service unavailable</h1><p className="mt-2 text-sm text-[#51483F]">The restaurant service is not configured for this site. Contact your site administrator.</p></div></div>;
  if (!userId) return <div data-admin-theme={theme} className="admin-theme min-h-screen bg-[#F6F5F2] p-4 text-[#211D19]"><div className="mx-auto flex w-full max-w-sm justify-end pt-4">{themeToggle}</div><div className="flex min-h-[calc(100vh-4rem)] items-center justify-center"><form onSubmit={(event) => void signIn(event)} className="w-full max-w-sm space-y-4 rounded-2xl border border-[#E8E2D9] bg-white p-6 shadow-sm"><div><h1 className="text-xl font-bold">Restaurant admin sign in</h1><p className="mt-1 text-sm text-[#51483F]">Sign in to manage {getPageRestaurantSlug()}.</p></div><label className="block text-sm font-semibold text-[#30271F]">Email<input required type="email" autoComplete="username" value={email} onChange={(event) => setEmail(event.target.value)} className="mt-1.5 min-h-11 w-full rounded-xl border border-[#BDB2A6] bg-white px-3 text-base font-normal text-[#211D19] placeholder:text-[#71675D] outline-none focus:border-[#8C5138] focus:ring-2 focus:ring-[#8C5138]/20" /></label><label className="block text-sm font-semibold text-[#30271F]">Password<input required type="password" autoComplete="current-password" value={password} onChange={(event) => setPassword(event.target.value)} className="mt-1.5 min-h-11 w-full rounded-xl border border-[#BDB2A6] bg-white px-3 text-base font-normal text-[#211D19] placeholder:text-[#71675D] outline-none focus:border-[#8C5138] focus:ring-2 focus:ring-[#8C5138]/20" /></label>{cloudError && <p role="alert" className="text-sm text-red-700">{cloudError}</p>}<button className="min-h-11 w-full rounded-xl bg-[#8C5138] font-bold text-white">Sign in</button><p className="text-xs leading-relaxed text-[#51483F]">Ask the site administrator to create your login and grant access to this restaurant.</p></form></div></div>;

  const content = () => {
    switch (section) {
      case 'menu': return <MenuManagerPage setup={setup} onChange={setSetup} />;
      case 'tables': return <TablesPage setup={setup} onChange={setSetup} />;
      case 'services': return <GuestServicesPage setup={setup} onChange={updateServices} onNavigate={setSection} />;
      case 'inbox': return <GuestInboxPage requests={requests} feedback={feedback} acknowledgingRequestId={acknowledgingRequestId} onAcknowledgeRequest={(id) => void acknowledgeRequest(id)} onFeedbackStatus={updateFeedback} />;
      case 'settings': return <RestaurantSettingsPage setup={setup} onChange={setSetup} />;
      default: return <OverviewPage setup={setup} requests={requests} feedback={feedback} onNavigate={setSection} />;
    }
  };

  const hasUnpublishedChanges = Boolean(savedSetupSnapshot) && setupSnapshot(setup) !== savedSetupSnapshot;
  return <div data-admin-theme={theme} className="admin-theme min-h-screen"><>{cloudError && <div role="alert" className="fixed bottom-4 right-4 z-50 max-w-md rounded-xl bg-red-50 p-4 text-sm text-red-800 shadow-lg">{cloudError}</div>}<AdminLayout theme={theme} onToggleTheme={() => setTheme((value) => value === 'light' ? 'dark' : 'light')} hasUnpublishedChanges={hasUnpublishedChanges} isPublishing={isPublishing} section={section} onSectionChange={(next) => { setSection(next); setNotice(''); const params = new URLSearchParams(window.location.search); params.set('section', next); window.history.replaceState(null, '', `/admin?${params.toString()}`); }} onSaveDraft={() => void saveDraft()} onPublish={() => void publish()} notice={notice} publishedAt={publishedAt} restaurantName={setup.restaurant.name} onSignOut={() => void supabase?.auth.signOut()} requestAlert={requestAlert} onAcknowledgeRequest={(id) => void acknowledgeRequest(id)} acknowledgingRequestId={acknowledgingRequestId} onViewRequestAlert={() => { setSection('inbox'); const params = new URLSearchParams(window.location.search); params.set('section', 'inbox'); window.history.replaceState(null, '', `/admin?${params.toString()}`); }} newRequestCount={requests.length}>{content()}</AdminLayout></></div>;
};
